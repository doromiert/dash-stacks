import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import St from 'gi://St';
import * as Main from 'resource:///org/gnome/shell/ui/main.js';

const delay = ms => new Promise(resolve => GLib.timeout_add(GLib.PRIORITY_DEFAULT, ms, () => {
    resolve();
    return GLib.SOURCE_REMOVE;
}));
const assert = (condition, message) => { if (!condition) throw new Error(message); };

export async function run(extension) {
    global.force_animations = true;
    const view = Main.overview._overview.controls.appDisplay;
    const settings = extension.getSettings();
    const folders = new Gio.Settings({schema_id: 'org.gnome.desktop.app-folders'});
    const folder = new Gio.Settings({schema_id: 'org.gnome.desktop.app-folders.folder',
        path: '/org/gnome/desktop/app-folders/folders/stacks-test/'});
    folder.set_string('name', 'Test Apps');
    folder.set_strv('apps', ['org.gnome.Nautilus.desktop', 'org.gnome.TextEditor.desktop']);
    folders.set_strv('folder-children', ['stacks-test']);
    view._redisplay();
    await delay(200);
    Main.overview.showApps();
    Main.overview.dash.showAppsButton.checked = true;
    await delay(700);
    const gridFolder = () => view.getAllItems().find(i => i.id === 'stacks-test');
    const dockFolder = () => extension._buttons.find(i => i.id === 'stacks-test');
    view._redisplay();
    await delay(200);
    assert(gridFolder(), 'folder initially missing from grid: ' + JSON.stringify({children:folders.get_strv('folder-children'), members:folder.get_strv('apps'), pins:settings.get_strv('pinned-app-folders'), favorites:global.settings.get_strv('favorite-apps'), items:view.getAllItems().map(i => i.id), infos:view.getAppInfos().map(i => i.get_id())}));
    assert(gridFolder().mapped, 'app grid folder is not on screen');
    const members = folder.get_strv('apps');
    const baselineMenu = extension._appFolderPins._menus.get(gridFolder());
    baselineMenu.rightClick.emit('recognize');
    assert(baselineMenu.menu.isOpen, 'right-click folder context menu did not open');
    baselineMenu.menu.close({animate: false});
    gridFolder().emit('popup-menu');
    assert(baselineMenu.menu.isOpen, 'keyboard folder context menu did not open');
    const pinAction = baselineMenu.menu._getMenuItems()[0];
    assert(pinAction.label.text === 'Pin to Dock', 'missing Pin to Dock action');
    const started = GLib.get_monotonic_time();
    pinAction.activate(null);
    await delay(80);
    const feedbackMs = (GLib.get_monotonic_time() - started) / 1000;
    assert(dockFolder()?.mapped, 'pin did not produce a mapped dock folder');
    assert(!gridFolder(), 'pinned folder remains in grid');
    assert(!view.getAllItems().some(i => members.includes(i.id)), 'folder member escaped into grid');
    assert(JSON.stringify(folder.get_strv('apps')) === JSON.stringify(members), 'pin changed membership');
    assert(dockFolder().getAppIds().length === 2, 'dock folder lost apps');
    await delay(100);
    const button = dockFolder();
    const size = button.get_size();
    const directory = extension._buttons.find(i => i.config);
    const directorySize = directory.get_size();
    assert(Math.abs(size[0] - size[1]) < 1, `app folder not square: ${size}`);
    assert(Math.abs(directorySize[0] - directorySize[1]) < 1, `directory stack not square: ${directorySize}`);
    const context = St.ThemeContext.get_for_stage(global.stage);
    const scale = context.scale_factor;
    context.scale_factor = 2;
    await delay(150);
    const scaledSize = dockFolder().get_size();
    const scaledDirectorySize = directory.get_size();
    assert(scaledSize[0] === scaledSize[1], `scaled app folder not square: ${scaledSize}`);
    assert(scaledDirectorySize[0] === scaledDirectorySize[1], `scaled directory not square: ${scaledDirectorySize}`);
    context.scale_factor = scale;
    await delay(150);
    button.open();
    await delay(350);
    assert(button._dialog._isOpen, 'native folder dialog did not open');
    assert(button.view.getAllItems().length === 2, 'native dialog has wrong app count');
    folder.set_string('name', 'Renamed Apps');
    folder.set_strv('apps', [members[0]]);
    await delay(100);
    assert(dockFolder().name === 'Renamed Apps', 'rename did not update');
    assert(dockFolder() === button && button._dialog._isOpen, 'editing destroyed the native folder dialog');
    assert(dockFolder().getAppIds().length === 1, 'membership did not update');
    button._dialog.popdown();
    await delay(300);
    settings.set_strv('pinned-app-folders', ['stacks-test', 'stacks-test', 'missing']);
    await delay(100);
    assert(extension._buttons.filter(i => i.id === 'stacks-test').length === 1, 'duplicate pin');
    assert(!extension._buttons.some(i => i.id === 'missing'), 'missing folder produced a dock entry');
    // Keep the folder but make it empty, then repopulate; watchers must survive an absent dock actor.
    folder.set_strv('apps', []);
    await delay(100);
    assert(!dockFolder(), 'empty folder produced a dock entry');
    folder.set_strv('apps', members);
    await delay(100);
    assert(dockFolder()?.getAppIds().length === 2, 'empty folder did not recover');
    extension.disable();
    await delay(100);
    assert(gridFolder(), 'disabling did not restore folder');
    extension.enable();
    await delay(150);
    assert(dockFolder() && !gridFolder(), 'pins not restored on re-enable');
    const pinned = dockFolder();
    pinned.emit('popup-menu');
    const unpin = extension._appFolderPins._menus.get(pinned).menu._getMenuItems()[0];
    assert(unpin.label.text === 'Unpin from Dock', 'missing Unpin action');
    unpin.activate(null);
    await delay(100);
    assert(gridFolder() && !dockFolder(), 'unpin did not restore folder');
    assert(JSON.stringify(folder.get_strv('apps')) === JSON.stringify(members), 'unpin changed membership');
    settings.set_strv('pinned-app-folders', ['stacks-test']);
    await delay(100);
    Main.overview.showApps();
    Main.overview.dash.showAppsButton.checked = true;
    await delay(400);
    dockFolder().add_style_pseudo_class('hover');
    extension._buttons.find(i => i.config).add_style_pseudo_class('hover');
    return {feedbackMs, size, directorySize, scaledSize, scaledDirectorySize, membersPreserved: true, lifecycle: true};
}
