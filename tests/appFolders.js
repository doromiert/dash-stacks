import Gio from 'gi://Gio';
import Clutter from 'gi://Clutter';
import GLib from 'gi://GLib';
import St from 'gi://St';
import * as Dash from 'resource:///org/gnome/shell/ui/dash.js';
import * as DND from 'resource:///org/gnome/shell/ui/dnd.js';
import * as Main from 'resource:///org/gnome/shell/ui/main.js';
const delay = ms => new Promise(resolve => GLib.timeout_add(GLib.PRIORITY_DEFAULT, ms, () => {resolve(); return GLib.SOURCE_REMOVE;}));
const assert = (condition, message) => { if (!condition) throw new Error(message); };
export async function run(extension) {
    global.force_animations = true;
    const view = Main.overview._overview.controls.appDisplay;
    const dash = Main.overview.dash;
    const settings = extension.getSettings();
    const folders = new Gio.Settings({schema_id:'org.gnome.desktop.app-folders'});
    const folder = new Gio.Settings({schema_id:'org.gnome.desktop.app-folders.folder',path:'/org/gnome/desktop/app-folders/folders/stacks-test/'});
    folder.set_string('name','Test Apps');
    const members = ['org.gnome.Nautilus.desktop','org.gnome.TextEditor.desktop'];
    folder.set_strv('apps',members);
    folders.set_strv('folder-children',['stacks-test']);
    view._redisplay();
    Main.overview.showApps();
    dash.showAppsButton.checked = true;
    await delay(800);
    const buttons = () => extension._buttons.filter(i => i._stackButton).map(i => i._stackButton);
    const appButton = () => buttons().find(i => i.config.appFolder === 'stacks-test');
    const gridFolder = () => view.getAllItems().find(i => i.id === 'stacks-test');
    const configs = () => JSON.parse(settings.get_string('stacks'));
    assert(gridFolder()?.mapped,'initial folder not in visible app grid');
    const menu = extension._appFolderPins._menus.get(gridFolder());
    menu.rightClick.emit('recognize');
    assert(menu.menu.isOpen,'right-click pin action missing');
    const started = GLib.get_monotonic_time();
    menu.menu._getMenuItems()[0].activate(null);
    await delay(100);
    const feedbackMs = (GLib.get_monotonic_time()-started)/1000;
    assert(appButton()?.mapped && !gridFolder(),'pin failed');
    assert(configs().some(i => i.appFolder === 'stacks-test'),'pin not in existing stacks list');
    assert(settings.get_strv('pinned-app-folders').length===0,'parallel pin model still used');
    assert(!view.getAllItems().some(i=>members.includes(i.id)),'member escaped folder');
    assert(JSON.stringify(folder.get_strv('apps'))===JSON.stringify(members),'membership changed');
    const directory = buttons().find(i=>i.config.path);
    assert(directory.constructor===appButton().constructor,'app folder uses a different stack component');
    assert(directory._dashItem instanceof Dash.DashItemContainer,'stack lacks native dock container');
    appButton().emit('clicked',1);
    await delay(100);
    assert(appButton().popup?.has_style_class_name('stack-popup-wrapper'),'app folder bypassed existing popup');
    const popupCount = button => button.popup.grid.get_children().reduce((n,row)=>n+row.get_n_children(),0);
    assert(popupCount(appButton())===2,'existing popup lost apps');
    appButton()._closePopup();
    await delay(200);
    const toggle = appButton()._menu._getMenuItems().find(i=>i.label?.text==='Show Folder Contents');
    assert(toggle,'existing show-contents control missing');
    toggle.emit('toggled',false);
    await delay(100);
    assert(!appButton().config.autoIcon && appButton().mainIcon instanceof St.Icon,'show-contents toggle not reused');
    appButton()._menu._getMenuItems().find(i=>i.label?.text==='Show Folder Contents').emit('toggled',true);
    await delay(100);
    assert(appButton().mainIcon.has_style_class_name('stack-auto-icon'),'contents preview not reused');
    const stack = appButton();
    stack._draggable.emit('drag-begin',0);
    stack._draggable.emit('drag-end',0,false);
    assert(configs().some(i=>i.appFolder==='stacks-test'),'cancelled drag removed pin');
    assert(view.handleDragOver(stack)===DND.DragMotionResult.MOVE_DROP,'grid rejects stack drag');
    assert(view.acceptDrop(stack),'drag from dock to grid failed');
    await delay(100);
    assert(gridFolder() && !appButton(),'drag-out did not restore folder');
    assert(dash.handleDragOver(gridFolder())===DND.DragMotionResult.MOVE_DROP,'dock rejects app-folder drag');
    assert(dash.acceptDrop(gridFolder()),'drag into dock failed');
    await delay(100);
    assert(appButton() && !gridFolder(),'drag-in failed');
    const dir = buttons().find(i=>i.config.path);
    assert(dir.acceptDrop(appButton(),null,0),'reorder drop rejected');
    await delay(100);
    assert(configs()[0].appFolder==='stacks-test','reorder did not persist');
    // Retain legacy pins on upgrade, without overwriting existing contents/icon choices.
    settings.set_strv('pinned-app-folders',['stacks-test']);
    extension.disable();
    extension.enable();
    await delay(150);
    assert(settings.get_strv('pinned-app-folders').length===0,'legacy pins not migrated');
    assert(configs().filter(i=>i.appFolder==='stacks-test').length===1,'migration duplicated pin');
    folder.set_strv('apps',[]);
    await delay(100);
    assert(!appButton(),'empty folder displayed');
    folder.set_strv('apps',members);
    await delay(100);
    assert(appButton(),'empty folder did not recover');
    // Real pointer gestures in the isolated VM, rather than only calling drop handlers.
    const pointer = global.stage.context.get_backend().get_default_seat().create_virtual_device(Clutter.InputDeviceType.POINTER_DEVICE);
    const center = actor => {
        const [x,y]=actor.get_transformed_position(), [w,h]=actor.get_transformed_size();
        return [x+w/2,y+h/2];
    };
    const drag = async (source, target) => {
        const start=center(source);
        pointer.notify_absolute_motion(GLib.get_monotonic_time(),...start);
        await delay(80);
        trace.push(['startPick',String(global.stage.get_actor_at_pos(Clutter.PickMode.REACTIVE,...start)),String(global.stage.get_grab_actor())]);
        pointer.notify_button(GLib.get_monotonic_time(),Clutter.BUTTON_PRIMARY,Clutter.ButtonState.PRESSED);
        await delay(60);
        for (let step=1; step<=20; step++) {
            pointer.notify_absolute_motion(GLib.get_monotonic_time(),start[0]+(target[0]-start[0])*step/20,start[1]+(target[1]-start[1])*step/20);
            await delay(15);
        }
        pointer.notify_button(GLib.get_monotonic_time(),Clutter.BUTTON_PRIMARY,Clutter.ButtonState.RELEASED);
        await delay(350);
    };
    const trace = [];
    const sourceButton = appButton();
    sourceButton._draggable.connect('drag-begin',()=>trace.push('begin'));
    sourceButton._draggable.connect('drag-end',(_d,...args)=>trace.push(['end',...args]));
    sourceButton.connect('destroy',()=>trace.push('source destroyed'));
    trace.push(['source',center(sourceButton),sourceButton.get_size(),sourceButton.mapped]);
    await drag(sourceButton, [200,400]);
    trace.push(['pointer',global.get_pointer(),String(global.stage.get_actor_at_pos(Clutter.PickMode.REACTIVE,200,400))]);
    assert(gridFolder() && !appButton(),'physical pointer drag-out failed: '+JSON.stringify(trace));
    await delay(500);
    const folderSource = gridFolder();
    view.goToPage(view._grid.getItemPage(folderSource), false);
    await delay(200);
    trace.push(['folder source',center(folderSource)]);
    folderSource._draggable.connect('drag-begin',()=>trace.push('folder begin'));
    folderSource._draggable.connect('drag-end',(_d,...args)=>trace.push(['folder end',...args]));
    await drag(folderSource,center(buttons().find(i=>i.config.path)));
    assert(appButton() && !gridFolder(),'physical pointer drag-in failed: '+JSON.stringify(trace));
    global.settings.set_strv('favorite-apps',['org.gnome.Calculator.desktop']);
    await delay(600);
    GLib.mkdir_with_parents('/tmp/stacks-dnd-folder', 0o700);
    let directoryButton = buttons().find(i=>i.config.path === '/tmp');
    directoryButton.emit('clicked',1);
    await delay(100);
    const folderItem = directoryButton.popup.grid.get_children().flatMap(row=>row.get_children()).find(i=>i._folderPath === '/tmp/stacks-dnd-folder');
    assert(folderItem && dash.acceptDrop(folderItem),'directory folder drop rejected');
    await delay(100);
    const directoryPin = buttons().find(i=>i.config.path === '/tmp/stacks-dnd-folder');
    assert(directoryPin,'directory folder not added to existing stacks');
    assert(view.acceptDrop(directoryPin),'directory stack drag-out rejected');
    await delay(100);
    assert(!configs().some(i=>i.path === '/tmp/stacks-dnd-folder'),'directory stack remained pinned');
    assert(Gio.File.new_for_path('/tmp/stacks-dnd-folder').query_exists(null),'drag-out deleted directory');
    await delay(500);
    const normal = dash._box.get_children().find(i=>i.child?.app);
    assert(normal,'normal pin missing for visual comparison');
    const color = actor => {actor.add_style_pseudo_class('hover');return actor.icon.get_theme_node().get_background_color().to_string();};
    const normalColor=color(normal.child), stackColor=color(appButton());
    assert(normalColor===stackColor,`hover color differs: ${normalColor}/${stackColor}`);
    normal.showLabel();
    appButton()._dashItem.showLabel();
    await delay(200);
    const gap = item => item.get_transformed_position()[1]-item.label.height-item.label.get_transformed_position()[1];
    const normalGap=gap(normal),stackGap=gap(appButton()._dashItem);
    assert(Math.abs(normalGap-stackGap)<1,`tooltip gap differs: ${normalGap}/${stackGap}`);
    normal.hideLabel();
    const size=appButton().icon.get_size(), directorySize=buttons().find(i=>i.config.path).icon.get_size();
    assert(size[0]===size[1] && directorySize[0]===directorySize[1],`non-square highlight ${size}/${directorySize}`);
    const context=St.ThemeContext.get_for_stage(global.stage), scale=context.scale_factor;
    context.scale_factor=2;
    await delay(100);
    const scaled=appButton().icon.get_size();
    assert(scaled[0]===scaled[1],`scaled highlight not square ${scaled}`);
    context.scale_factor=scale;
    await delay(100);
    return {feedbackMs,size,directorySize,scaled,normalSize:normal.child.icon.get_size(),normalColor,stackColor,normalGap,stackGap,sharedStackModel:true,dragInOutReorder:true,physicalPointerDrag:true,migration:true,membersPreserved:true,lifecycle:true};
}
